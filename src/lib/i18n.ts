function deviceLang(): 'de' | 'en' {
  try {
    const forced = process.env.EXPO_PUBLIC_LANG;
    if (forced === 'de' || forced === 'en') return forced;
    const code = getLocales()[0]?.languageCode?.toLowerCase();
    return code === 'de' ? 'de' : 'en';
  } catch {
    return 'en';
  }
}

export const lang = deviceLang();
const dict: Record<Key, string> = lang === 'de' ? de : en;

export function t(key: Key, params?: Record<string, string | number>) {
  let s = dict[key] ?? en[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** Text zu einem API-Fehler (nach `error`-Code); unbekannte Codes → Text vom Server oder allgemeiner Fehler. */
export function errorText(e: unknown) {
  const code = (e as { code?: string })?.code;
  const key = `err.${code}` as Key;
  if (code && key in en) return t(key);
  const msg = (e as { message?: string })?.message;
  return msg && msg !== code ? msg : t('err.server_error');
}

export const isKey = (k: string): k is Key => k in en;
